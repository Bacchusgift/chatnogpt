package turtlesoup

import "strconv"

// 内置故事本：经典海龟汤谜题，owner 为空表示系统故事（谜底仅在开局时下发给主持人，
// 结束后全员可见）。用户可在插件详情页或游戏面板上传自己的故事本。

func seedStories() []*Story {
	base := nowUnix() - 86400 // 固定较早时间，保证排序稳定（系统故事在前）
	riddles := []struct{ riddle, answer string }{
		{
			"男人走进一家海边餐厅，点了一份海龟汤。他喝了一口，放下勺子结账离开，回到家后自杀了。为什么？",
			"男人曾遭遇海难，与同伴漂流到荒岛，濒临饿死时同伴端来「海龟汤」救了他。这次他在餐厅喝到真正的海龟汤，发现味道和当年完全不同——当年喝的其实是用死去同伴的肉做的汤。得知真相后他无法承受，选择了自杀。",
		},
		{
			"荒野中央躺着一具男尸，手里紧紧攥着半根火柴，周围没有任何脚印和打斗痕迹。他是怎么死的？",
			"男人和同伴乘坐热气球旅行，途中气球不断漏气下降，必须有人离开才能保住其他人。他们抽签决定谁跳下去，抽到半根火柴的人就是他——带着火柴从高空坠落。",
		},
		{
			"男人走进酒吧，向酒保要了一杯水。酒保突然拔出枪指着他。男人愣了几秒，随后说「谢谢你」，微笑着离开了。发生了什么？",
			"男人当时在打嗝，想喝水止住。酒保看出他的窘迫，故意用枪指着他吓了他一跳——打嗝瞬间好了。男人明白酒保是在用这个办法帮他，所以真诚道谢后离开。",
		},
		{
			"一个男人全身湿透地死在树下。当时没有下雨，附近也没有水源，他身上没有伤口。他是怎么死的？",
			"他刚从湖里潜水上岸，浑身湿透，坐在树下晾晒身体。恰在此时一道闪电击中了这棵树，他被雷电击中身亡。全身湿透反而让雷击更容易致命，而当时并没有下雨。",
		},
		{
			"芭蕾舞演员正在舞台上表演，音乐突然戛然而止，她当场死亡。台下观众什么都没做，舞台上也没有任何人碰她。她是怎么死的？",
			"她是一位盲人芭蕾舞演员，一直靠乐队现场演奏的音乐节奏完成高难度动作。乐队误以为她已退场，提前停止了演奏，她瞬间失去节奏和方位判断，从舞台高台坠落身亡。",
		},
		{
			"住在大厦 20 层的侏儒每天下楼买东西。奇怪的是：下楼没问题，回来却只坐电梯到 9 层，然后爬 11 层楼梯回家。但下雨天，他能直接坐电梯到家。为什么？",
			"侏儒个子太矮，手指只够得到电梯里 9 楼的按钮，所以平时只能坐到 9 层再爬楼梯。下雨天他带了伞，可以用伞尖捅到 20 楼的按钮，直接坐电梯回家。",
		},
	}
	out := []*Story{}
	for i, r := range riddles {
		out = append(out, &Story{
			ID:        "sys" + fmtSprint(i),
			OwnerID:   "",
			Riddle:    r.riddle,
			Answer:    r.answer,
			CreatedAt: base + int64(i),
		})
	}
	return out
}

func fmtSprint(i int) string { return strconv.Itoa(i) }
